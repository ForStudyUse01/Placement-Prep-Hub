// Build-time verifier for the Debugging Arena data.
// Usage: node tools/verify-debug.mjs
// - Runs Python and JavaScript "fixed" and "bugged" programs on every test case.
// - Python and JS fixed outputs must agree; they become the expected outputs.
// - Every bug must actually make Python and JS fail (wrong output, crash or syntax error).
// - Every bug patch must apply to all five languages; fixed code braces must balance.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { pathToFileURL } from "node:url";
import { assemble } from "../js/data/debug/templates.js";

const dir = path.resolve("js/data/debug");
const files = fs.readdirSync(dir).filter((f) => /^p\d+\.js$/.test(f)).sort();
const problems = [];
for (const f of files) {
  const mod = await import(pathToFileURL(path.join(dir, f)).href);
  for (const v of Object.values(mod)) problems.push(...v);
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "dbg-"));
const LANGS = ["py", "js", "c", "cpp", "java"];
const errors = [];
const expectedOut = {};
let n = 0;

const applyBug = (code, pairs) => {
  let out = code;
  for (const [from, to] of pairs) {
    if (!out.includes(from)) return null;
    out = out.replace(from, to);
  }
  return out;
};

function run(lang, program, stdin) {
  const file = path.join(tmp, lang === "py" ? "m.py" : "m.cjs");
  const src = lang === "js" ? `const readAll = () => require("fs").readFileSync(0, "utf8");\n${program}` : program;
  fs.writeFileSync(file, src);
  const r = spawnSync(lang === "py" ? "python" : "node", [file], { input: stdin, encoding: "utf8", timeout: 10000 });
  if (r.status !== 0) return { error: (r.stderr || String(r.error || "")).split("\n").filter(Boolean).slice(-2).join(" | ") || "exit " + r.status };
  return { lines: r.stdout.trim().split("\n").map((s) => s.trim()) };
}

const ids = new Set();
for (const p of problems) {
  n++;
  if (ids.has(p.id)) errors.push(`${p.id}: duplicate id`);
  ids.add(p.id);
  const all = [...p.cases, ...p.hidden];
  const stdin = `${all.length}\n${all.join("\n")}\n`;

  const fixed = {}, bugged = {};
  for (const l of LANGS) {
    if (!p[l]) { errors.push(`${p.id}: missing ${l}`); continue; }
    const [code, pairs] = p[l];
    const b = applyBug(code, pairs);
    if (b === null) { errors.push(`${p.id}/${l}: bug pattern not found in fixed code`); continue; }
    if (b === code) errors.push(`${p.id}/${l}: bug does not change code`);
    const bare = code.replace(/'(?:\\.|[^'\\])'/g, "").replace(/"(?:\\.|[^"\\])*"/g, "");
    const open = (bare.match(/{/g) || []).length, close = (bare.match(/}/g) || []).length;
    if (open !== close) errors.push(`${p.id}/${l}: unbalanced braces in fixed code`);
    fixed[l] = assemble(l, p.kind, code);
    bugged[l] = assemble(l, p.kind, b);
  }
  if (!fixed.py || !fixed.js) continue;

  const py = run("py", fixed.py, stdin), js = run("js", fixed.js, stdin);
  if (py.error) { errors.push(`${p.id}: python fixed crashed: ${py.error}`); continue; }
  if (js.error) { errors.push(`${p.id}: js fixed crashed: ${js.error}`); continue; }
  if (py.lines.length !== all.length) { errors.push(`${p.id}: python printed ${py.lines.length} lines for ${all.length} cases`); continue; }
  if (JSON.stringify(py.lines) !== JSON.stringify(js.lines)) { errors.push(`${p.id}: python vs js differ: ${JSON.stringify(py.lines)} vs ${JSON.stringify(js.lines)}`); continue; }
  expectedOut[p.id] = py.lines;

  for (const l of ["py", "js"]) {
    const r = run(l, bugged[l], stdin);
    const failsSomething = r.error || JSON.stringify(r.lines) !== JSON.stringify(py.lines);
    if (!failsSomething) errors.push(`${p.id}/${l}: BUG DOES NOT FAIL any test`);
    if (p.bug.type === "syntax" && !r.error) errors.push(`${p.id}/${l}: syntax bug did not raise an error`);
    if (p.bug.type !== "syntax" && r.error && !/Error|error/.test(r.error)) errors.push(`${p.id}/${l}: odd error ${r.error}`);
  }
  // visible cases should show at least two different outputs, so a constant answer cannot pass
  if (new Set(py.lines).size < 2) errors.push(`${p.id}: all expected outputs identical`);
}

fs.rmSync(tmp, { recursive: true, force: true });
const out = `// GENERATED by tools/verify-debug.mjs. Do not edit by hand.\nexport const EXPECTED = ${JSON.stringify(expectedOut, null, 0).replace(/\],"/g, "],\n\"")};\n`;
fs.writeFileSync(path.join(dir, "expected.js"), out);
console.log(`${n} problems checked, ${errors.length} problem(s) found`);
errors.forEach((e) => console.log(" -", e));
process.exit(errors.length ? 1 : 0);
