export const fnName = (sig) => sig.split("(")[0].trim();
export const fmtCase = (p, c, lang) => {
  const name = fnName(lang === "Python" ? p.py : p.js);
  const show = (v) => (lang === "Python" ? JSON.stringify(v).replace(/\bnull\b/g, "None").replace(/\btrue\b/g, "True").replace(/\bfalse\b/g, "False") : JSON.stringify(v));
  const call = p.kind === "lru" ? `LRUCache(${c.args[0]}) then ops ${JSON.stringify(c.args[1])}` : `${name}(${c.args.map(show).join(", ")})`;
  return [call, show(c.expected)];
};
